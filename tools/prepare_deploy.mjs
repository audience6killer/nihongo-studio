#!/usr/bin/env node
/* prepare_deploy.mjs — build the static site into deploy/.
 *
 * Node standard library only: this project has no installable dependencies.
 *
 *   node tools/prepare_deploy.mjs
 *
 * What it does
 *   1. wipes deploy/ and copies the app files in
 *   2. writes assets/js/data/config.js from the environment (empty when unset)
 *   3. hashes every deployed file except sw.js and stamps that digest into the
 *      service worker's cache name, so a deploy can never serve a stale cache
 *   4. refuses to finish if the service worker's CORE list names a missing file,
 *      or if anything secret-looking ended up in the output
 */
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEPLOY = join(ROOT, 'deploy');

const TOP_FILES = ['index.html', 'manifest.webmanifest', 'sw.js', 'setup.html'];
const ASSET_DIR = 'assets';
const SKIP_DIRS = new Set(['.git', 'deploy', 'node_modules', 'scratch']);

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) {
      if (SKIP_DIRS.has(name)) continue;
      walk(full, out);
    } else {
      out.push(full);
    }
  }
  return out;
}

function rel(p) {
  return relative(ROOT, p).split('\\').join('/');
}

function copyInto(relPath) {
  const src = join(ROOT, relPath);
  const dest = join(DEPLOY, relPath);
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(src, dest);
}

function sha256(text) {
  return createHash('sha256').update(text).digest('hex');
}

console.log('prepare_deploy');

// 1 ── clean and copy
rmSync(DEPLOY, { recursive: true, force: true });
mkdirSync(DEPLOY, { recursive: true });

for (const name of TOP_FILES) {
  if (!existsSync(join(ROOT, name))) {
    console.error(`  x ${name} is missing from the project root`);
    process.exit(1);
  }
  copyInto(name);
}

const assetRoot = join(ROOT, ASSET_DIR);
if (!existsSync(assetRoot)) {
  console.error('  x assets/ is missing');
  process.exit(1);
}
const assetFiles = walk(assetRoot).map(rel);
for (const f of assetFiles) copyInto(f);
console.log(`  copied ${TOP_FILES.length + assetFiles.length} files`);

// 2 ── build-time configuration
const supabaseUrl = (process.env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const anonKey = (process.env.SUPABASE_ANON_KEY || '').trim();
if (!!supabaseUrl !== !!anonKey) {
  console.error('  x Set both SUPABASE_URL and SUPABASE_ANON_KEY, or neither.');
  process.exit(1);
}
if (supabaseUrl && !/^https?:\/\//.test(supabaseUrl)) {
  console.error('  x SUPABASE_URL must start with https://');
  process.exit(1);
}
if (/service_role|secret/i.test(anonKey)) {
  console.error('  x SUPABASE_ANON_KEY looks like a secret key. Only the anon/publishable key may be shipped.');
  process.exit(1);
}
const configPath = join(DEPLOY, 'assets', 'js', 'data', 'config.js');
writeFileSync(
  configPath,
  `/* Generated by tools/prepare_deploy.mjs at build time.
 * Everything here is public by design: the anon/publishable key is protected by
 * Row Level Security. Never put a secret or service_role key in this file.
 */
window.NJ_CONFIG = {
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(anonKey)},
  builtAt: ${JSON.stringify(new Date().toISOString())},
  release: '__RELEASE__'
};
`,
  'utf8'
);
console.log(`  supabase: ${supabaseUrl ? 'configured at build time' : 'not configured (manual Settings)'}`);

// 2b ── inject the schema into the setup guide
const setupPath = join(DEPLOY, 'setup.html');
if (existsSync(setupPath)) {
  const schema = readFileSync(join(ROOT, 'supabase', 'schema.sql'), 'utf8');
  const escapeHtml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  let setup = readFileSync(setupPath, 'utf8');
  if (/<pre id="sql">[\s\S]*?<\/pre>/.test(setup)) {
    setup = setup.replace(/<pre id="sql">[\s\S]*?<\/pre>/, `<pre id="sql">${escapeHtml(schema)}</pre>`);
  } else {
    console.error('  x setup.html lost its <pre id="sql"> placeholder');
    process.exit(1);
  }
  writeFileSync(setupPath, setup, 'utf8');
  console.log('  setup.html: schema injected');
} else {
  console.log('  setup.html: not present, skipped');
}

// 3 ── hash and stamp the service worker
const deployFiles = walk(DEPLOY).map((p) => relative(DEPLOY, p).split('\\').join('/')).sort();
const hash = createHash('sha256');
let bytes = 0;
for (const f of deployFiles) {
  if (f === 'sw.js') continue;
  const buf = readFileSync(join(DEPLOY, f));
  bytes += buf.length;
  hash.update(f);
  hash.update(buf);
}
const release = 'nj-' + hash.digest('hex').slice(0, 10);

const swPath = join(DEPLOY, 'sw.js');
let sw = readFileSync(swPath, 'utf8');
if (!/const RELEASE = '[^']*';/.test(sw)) {
  console.error('  x sw.js lost its RELEASE constant');
  process.exit(1);
}
sw = sw.replace(/const RELEASE = '[^']*';/, `const RELEASE = '${release}';`);
writeFileSync(swPath, sw, 'utf8');

// the config carries the same release so Settings can show it
const cfg = readFileSync(configPath, 'utf8').replace('__RELEASE__', release);
writeFileSync(configPath, cfg, 'utf8');

console.log(`  release ${release}`);

// 4 ── the service worker's CORE list must match what actually shipped
const coreMatch = /const CORE = \[([\s\S]*?)\];/.exec(sw);
if (!coreMatch) {
  console.error('  x could not read the CORE list from sw.js');
  process.exit(1);
}
const core = [...coreMatch[1].matchAll(/'([^']+)'/g)].map((m) => m[1]).filter((p) => p !== './');
const missing = core.filter((p) => !existsSync(join(DEPLOY, p)));
if (missing.length) {
  console.error('  x sw.js CORE names files that were not deployed:');
  for (const m of missing) console.error(`      ${m}`);
  process.exit(1);
}
// Cached through the SHELL constant, or deliberately outside the offline shell.
const IMPLICIT = new Set(['sw.js', 'index.html', 'setup.html', 'assets/js/data/config.js']);
const uncached = deployFiles.filter((f) => !IMPLICIT.has(f) && !core.includes(f));
if (uncached.length) {
  console.warn(`  ! ${uncached.length} deployed file(s) are not in the CORE list: ${uncached.slice(0, 5).join(', ')}`);
}

// 5 ── nothing secret, nothing that should not ship
// Look for real secret material: JWTs, the service-role env var, a quoted
// service_role value, or a private key block. A plain mention of the word
// "service_role" in a warning comment is fine and must not trip this.
const FORBIDDEN = [
  /eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{10,}/,
  /SUPABASE_SERVICE/,
  /["']service_role["']/,
  /BEGIN [A-Z ]*PRIVATE KEY/
];
const leaked = [];
for (const f of deployFiles) {
  const text = readFileSync(join(DEPLOY, f), 'utf8');
  for (const re of FORBIDDEN) {
    if (re.test(text)) leaked.push(`${f} matches ${re}`);
  }
}
if (leaked.length) {
  console.error('  x secret-shaped content in the deploy:');
  for (const l of leaked) console.error(`      ${l}`);
  process.exit(1);
}

console.log(`  deploy/ ready — ${deployFiles.length} files, ${(bytes / 1024).toFixed(0)} KB`);
console.log(`  serve it locally:  python serve.py --root deploy --port 8770`);
